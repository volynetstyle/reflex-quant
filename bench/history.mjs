// Historical trajectory of the graph scenarios (bench/scenarios.mjs) over CI.
//
//   node bench/history.mjs [--repo owner/name] [--out research/HISTORY.md]
//
// Needs the GitHub CLI (gh), authenticated. For every successful run of the
// Experiment workflow (one job, artifact `experiment`) and of the Benchmark
// workflow (shards `scenarios-*`), it downloads the timing JSON once into
// .cache/history/<run>/ and keeps, per scenario, the ratios measured inside
// one job: quant / Reflex and quant / alien. Absolute times are not compared:
// runners differ in CPU from run to run, and even between shards of one run.
// A run's summary is the geometric mean of its ratios over the scenarios it
// timed, and the counts of scenarios within 25 % of the better of Reflex and
// alien-signals and faster than both.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const args = process.argv.slice(2);
const option = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
const repo = option("--repo", "volynetstyle/reflex-quant");
const outFile = option("--out", path.join(root, "research/HISTORY.md"));
const cache = path.join(root, ".cache/history");

const gh = (...a) => execFileSync("gh", a, { encoding: "utf8", maxBuffer: 1 << 26 });
const runs = JSON.parse(
  gh("run", "list", "--repo", repo, "--limit", "200", "--json", "databaseId,workflowName,headSha,conclusion,createdAt,displayTitle"),
)
  .filter((r) => (r.workflowName === "Experiment" || r.workflowName === "Benchmark") && r.conclusion === "success")
  .sort((a, b) => a.createdAt.localeCompare(b.createdAt));

function timings(run) {
  const dir = path.join(cache, String(run.databaseId));
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
    const patterns = run.workflowName === "Experiment" ? ["experiment"] : ["scenarios-*"];
    for (const p of patterns) {
      try {
        execFileSync("gh", ["run", "download", String(run.databaseId), "--repo", repo, "--pattern", p, "--dir", dir], { stdio: "ignore" });
      } catch {
        // Expired or absent artifacts leave the directory empty.
      }
    }
  }
  const files = [];
  const walk = (d) => {
    for (const f of readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, f.name);
      if (f.isDirectory()) walk(p);
      else if (/^(timing|scenarios-[\w-]+)\.json$/.test(f.name)) files.push(p);
    }
  };
  walk(dir);
  const rows = {};
  const cpus = new Set();
  for (const f of files) {
    const data = JSON.parse(readFileSync(f, "utf8"));
    if (data.env?.cpu) cpus.add(data.env.cpu.replace(/\s+\d+-Core Processor|\(R\)|\(TM\)| CPU @ [\d.]+GHz/g, "").trim());
    for (const r of data.rows ?? []) {
      if (r.quantVsReflex === undefined) continue;
      rows[r.id] = { reflex: r.quantVsReflex, alien: r.quantVsAlien, best: r.quantVsBest };
    }
  }
  return { rows, cpus: [...cpus] };
}

const geomean = (xs) => Math.exp(xs.reduce((a, x) => a + Math.log(x), 0) / xs.length);
const history = [];
for (const run of runs) {
  const { rows, cpus } = timings(run);
  const ids = Object.keys(rows);
  if (ids.length === 0) continue;
  history.push({
    run: run.databaseId,
    workflow: run.workflowName,
    commit: run.headSha.slice(0, 7),
    date: run.createdAt,
    title: run.displayTitle,
    cpus,
    scenarios: ids.length,
    vsReflex: geomean(ids.map((id) => rows[id].reflex)),
    vsAlien: geomean(ids.map((id) => rows[id].alien)),
    vsBest: geomean(ids.map((id) => rows[id].best)),
    within25: ids.filter((id) => rows[id].best <= 1.25).length,
    fasterThanBoth: ids.filter((id) => rows[id].best < 1).length,
    rows,
  });
}
mkdirSync(cache, { recursive: true });
writeFileSync(path.join(cache, "history.json"), JSON.stringify(history, null, 2) + "\n");

// Report.
const f2 = (x) => (Number.isFinite(x) ? x.toFixed(2) : "—");
const scenarioIds = [...new Set(history.flatMap((h) => Object.keys(h.rows)))];
const lines = [
  "# Performance history on CI",
  "",
  `Generated by \`node bench/history.mjs\` from ${history.length} successful runs of the Experiment and Benchmark workflows (${repo}).`,
  "Every number is a ratio measured inside one CI job (quant / Reflex, quant / alien-signals; below 1 is faster than the other runtime).",
  "Runners change CPU between runs, and the scenarios' code changed over time, so read trends, not single steps.",
  "",
  "## Per run",
  "",
  "| date (UTC) | commit | run | CPU | scenarios | geomean vs best | geomean vs Reflex | geomean vs alien | within 25 % of best | faster than both |",
  "| --- | --- | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
  ...history.map(
    (h) =>
      `| ${h.date.slice(0, 16).replace("T", " ")} | \`${h.commit}\` | ${h.run} | ${h.cpus.join(", ") || "—"} | ${h.scenarios} | ${f2(h.vsBest)} | ${f2(h.vsReflex)} | ${f2(h.vsAlien)} | ${h.within25} | ${h.fasterThanBoth} |`,
  ),
  "",
  "## Per scenario: quant / Reflex",
  "",
  `| scenario | ${history.map((h) => `\`${h.commit}\``).join(" | ")} |`,
  `| --- | ${history.map(() => "---:").join(" | ")} |`,
  ...scenarioIds.map((id) => `| ${id} | ${history.map((h) => f2(h.rows[id]?.reflex)).join(" | ")} |`),
  "",
  "## Commits",
  "",
  ...history.map((h) => `- \`${h.commit}\` (${h.workflow} ${h.run}): ${h.title}`),
  "",
];
writeFileSync(outFile, lines.join("\n"));

